"""Regenerate image_sizes.py from the Commons API.

Run from this directory after adding a city or editing the atlas section:

    python3 refresh_image_sizes.py

build_index.py needs each source file's real pixel width so it never asks the
thumbnailer for a size the file cannot fill. Nothing here touches the network
at build time; this script is the only part that does.
"""
import json
import os
import re
import subprocess
import urllib.parse

HERE = os.path.dirname(os.path.abspath(__file__))
API = "https://commons.wikimedia.org/w/api.php"
UA = "mithaify-image-sizes/1.0 (https://mithaify.vercel.app)"

FILE_RE = re.compile(
    r'https://upload\.wikimedia\.org/wikipedia/commons/'
    r'(?:thumb/)?[0-9a-f]/[0-9a-f]{2}/([^/"\s]+)'
)


def source_urls():
    import sys
    sys.path.insert(0, HERE)
    from cities import CITIES, HERO_PHOTO

    urls = [HERO_PHOTO]
    for c in CITIES:
        urls += [c["bg"], c["landmark_img"]]
    with open(os.path.join(HERE, "current_atlas_section.html"), encoding="utf-8") as f:
        urls += re.findall(r'src="(https://upload\.wikimedia\.org/[^"]+)"', f.read())
    return urls


def filenames(urls):
    names = set()
    for u in urls:
        m = FILE_RE.match(u)
        if m:
            # the thumb path repeats the filename in the last segment; the
            # captured group is the directory form, which is the real name
            names.add(urllib.parse.unquote(m.group(1)))
    return sorted(names)


def fetch_widths(names):
    # Shells out to curl rather than urllib: the system pythons here have no
    # usable CA bundle, and curl already trusts the system roots.
    widths = {}
    for i in range(0, len(names), 40):
        batch = names[i:i + 40]
        query = urllib.parse.urlencode({
            "action": "query", "format": "json", "prop": "imageinfo",
            "iiprop": "size", "titles": "|".join("File:" + n for n in batch),
        })
        out = subprocess.run(
            ["curl", "-sS", "--fail", "--max-time", "60", "-A", UA, f"{API}?{query}"],
            check=True, capture_output=True, text=True).stdout
        for page in json.loads(out)["query"]["pages"].values():
            info = page.get("imageinfo", [{}])[0]
            if info.get("width"):
                # API titles use spaces where URLs use underscores
                widths[page["title"].removeprefix("File:").replace(" ", "_")] = info["width"]
    return widths


def main():
    names = filenames(source_urls())
    widths = fetch_widths(names)
    missing = [n for n in names if n not in widths]
    if missing:
        raise SystemExit("no imageinfo for: " + ", ".join(missing))

    out = os.path.join(HERE, "image_sizes.py")
    with open(out, "w", encoding="utf-8") as f:
        f.write('"""Original pixel widths of every Wikimedia Commons file used on the site.\n\n'
                "Generated by refresh_image_sizes.py -- do not edit by hand.\n\n"
                "images.py uses these to cap every generated thumbnail width, so a URL is\n"
                "never built for a size larger than the source file can fill.\n\n"
                "Keys are the filename as it appears in the URL, i.e. underscores not spaces.\n"
                '"""\n\nSOURCE_WIDTHS = {\n')
        for name in sorted(widths):
            f.write(f"    {name!r}: {widths[name]},\n")
        f.write("}\n")
    print(f"wrote {out} - {len(widths)} files")


if __name__ == "__main__":
    main()
